#!/usr/bin/env node
// Emits OBS-compatible GLSL/Cg source from the same checked-in GLSL used by WebGL preview.
// No network, code fetching, or evaluation of untrusted inputs.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const repo = path.resolve(__dirname, '..');
const source = path.join(repo,'tools/shader-builder/nodes/colormap-kernels.js');
const ctx = vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(source,'utf8'),ctx,{filename:source,timeout:2000});
const kernels = ctx.window.COLORMAP_KERNELS;
const expected = ['colormapJet','colormapSpectral','colormapLavaWaves','colormapSpace'];
if (!kernels || expected.some((name)=>typeof kernels[name] !== 'string') ||
    Object.keys(kernels).length !== expected.length) {
  throw new Error('Unexpected colormap kernel registry');
}
// Standard library already defines vec4 -> float4 for OBS native HLSL/Cg.
// The same formula body is used in WebGL without translation.
const output = `// Derived from kbinani/colormap-shaders, commit 3ba464481acfdd30bb33ac00503190d99398979f
// Copyright (c) 2015 kbinani. MIT License (see COLORMAPS-LICENSE.txt).
// Generated by scripts/generate-colormaps.js. Do not edit this file by hand.
// Input expected within [0,1]; output is opaque RGB(A).
#ifndef HYPERSHADER_COLORMAPS_H
#define HYPERSHADER_COLORMAPS_H

${expected.map(name => kernels[name]).join('\n\n')}

#endif
`;
const target = path.join(repo,'data/stdlib/colormaps.glsl');
if(process.argv.includes('--check')){
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) {
    console.error('FAIL: generated native colormaps out of sync');
    process.exit(1);
  }
  console.log('PASS: canonical GLSL and native colormaps in sync');
} else {
  fs.writeFileSync(target,output);
  console.log('Wrote',target);
}
