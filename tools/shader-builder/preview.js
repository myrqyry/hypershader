/**
 * Lightweight WebGL2 preview for the standalone HyperShaderFX graph editor.
 * Only buildPreviewShader()'s explicit browser-supported subset runs here.
 * This is not OBS's .effect compiler or its GPU runtime.
 */
class ShaderPreviewRenderer {
    constructor(canvas) {
        this.canvas = canvas;
        this.gl = canvas.getContext('webgl2', {
            alpha: false, antialias: false, premultipliedAlpha: false,
            preserveDrawingBuffer: true
        });
        if (!this.gl) throw new Error('WebGL2 is unavailable for the browser preview');
        const gl = this.gl;
        this.program = null;
        this.vertexArray = gl.createVertexArray();
        this.sourceTexture = gl.createTexture();
        if (!this.vertexArray || !this.sourceTexture) {
            throw new Error('WebGL2 could not allocate preview resources');
        }
        gl.bindVertexArray(this.vertexArray);
        gl.activeTexture(gl.TEXTURE0);
        gl.bindTexture(gl.TEXTURE_2D, this.sourceTexture);
        const size = 64;
        const pixels = new Uint8Array(size * size * 4);
        for (let y = 0; y < size; y++) {
            for (let x = 0; x < size; x++) {
                const k = (y * size + x) * 4;
                const checker = (Math.floor(x / 8) + Math.floor(y / 8)) % 2;
                pixels[k] = Math.round(255 * x / (size - 1));
                pixels[k + 1] = Math.round(255 * y / (size - 1));
                pixels[k + 2] = checker ? 200 : 50;
                pixels[k + 3] = 255;
            }
        }
        gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA8, size, size, 0, gl.RGBA, gl.UNSIGNED_BYTE, pixels);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.LINEAR);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.LINEAR);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
    }

    // WebGL compiler logs usually report 0:line: (Mesa/ANGLE) or 0(line).
    // Locate the enclosing emitted node section without blaming a nearby
    // node for an error in the shader header or generated boilerplate.
    static describeCompileError(message, source) {
        const nodes = new Map();
        let current = null;
        source.split(/\r?\n/).forEach((text, index) => {
            const marker = text.match(/^\s*\/\/ @node ([a-zA-Z0-9_-]+) ([a-zA-Z0-9_-]+)$/);
            if (marker) {
                current = { id: marker[1], type: marker[2] };
            } else if (/^\s*\/\/ @endnode$/.test(text)) {
                current = null;
            } else if (current) {
                nodes.set(index + 1, current);
            }
        });
        const seen = new Set();
        const matches = String(message).matchAll(/(?:\b(?:ERROR|WARNING):\s*\d+:(\d+):|\b\d+\((\d+)\))/g);
        const notes = [];
        for (const match of matches) {
            const origin = nodes.get(Number(match[1] || match[2]));
            if (!origin || seen.has(origin.id)) continue;
            seen.add(origin.id);
            notes.push(`Generated by node ${origin.id} (${origin.type})`);
        }
        return notes.length ? `${message}\n${notes.join('\n')}` : String(message);
    }

    compile(type, source) {
        const gl = this.gl;
        const shader = gl.createShader(type);
        if (!shader) throw new Error('WebGL2 shader allocation failed');
        gl.shaderSource(shader, source);
        gl.compileShader(shader);
        if (!gl.getShaderParameter(shader, gl.COMPILE_STATUS)) {
            const message = gl.getShaderInfoLog(shader) || 'unknown error';
            gl.deleteShader(shader);
            throw new Error('WebGL2 shader compile error: ' + ShaderPreviewRenderer.describeCompileError(message, source));
        }
        return shader;
    }

    setShader(source) {
        const gl = this.gl;
        const vertexSource = [
            '#version 300 es',
            'void main() {',
            '  vec2 p = gl_VertexID == 0 ? vec2(-1.0, -1.0)',
            '         : gl_VertexID == 1 ? vec2(3.0, -1.0) : vec2(-1.0, 3.0);',
            '  gl_Position = vec4(p, 0.0, 1.0);',
            '}'
        ].join('\n');
        let vertex = null;
        let fragment = null;
        let candidate = null;
        try {
            vertex = this.compile(gl.VERTEX_SHADER, vertexSource);
            fragment = this.compile(gl.FRAGMENT_SHADER, source);
            candidate = gl.createProgram();
            if (!candidate) throw new Error('WebGL2 program allocation failed');
            gl.attachShader(candidate, vertex);
            gl.attachShader(candidate, fragment);
            gl.linkProgram(candidate);
            if (!gl.getProgramParameter(candidate, gl.LINK_STATUS)) {
                throw new Error('WebGL2 program link error: ' + (gl.getProgramInfoLog(candidate) || 'unknown error'));
            }
            if (this.program) gl.deleteProgram(this.program);
            this.program = candidate;
            candidate = null;
        } finally {
            if (candidate) gl.deleteProgram(candidate);
            if (vertex) gl.deleteShader(vertex);
            if (fragment) gl.deleteShader(fragment);
        }
    }

    clear() {
        const gl = this.gl;
        if (this.program) gl.deleteProgram(this.program);
        this.program = null;
        gl.viewport(0, 0, gl.drawingBufferWidth, gl.drawingBufferHeight);
        gl.clearColor(0, 0, 0, 1);
        gl.clear(gl.COLOR_BUFFER_BIT);
    }

    renderFrame(milliseconds) {
        if (!this.program) return;
        const gl = this.gl;
        const scale = typeof devicePixelRatio === 'number' ? Math.min(devicePixelRatio, 2) : 1;
        const rect = this.canvas.getBoundingClientRect();
        const width = Math.max(1, Math.round((rect.width || this.canvas.width) * scale));
        const height = Math.max(1, Math.round((rect.height || this.canvas.height) * scale));
        if (this.canvas.width !== width || this.canvas.height !== height) {
            this.canvas.width = width;
            this.canvas.height = height;
        }
        gl.viewport(0, 0, width, height);
        gl.useProgram(this.program);
        gl.bindVertexArray(this.vertexArray);
        gl.activeTexture(gl.TEXTURE0);
        gl.bindTexture(gl.TEXTURE_2D, this.sourceTexture);
        gl.uniform1i(gl.getUniformLocation(this.program, 'uSource'), 0);
        gl.uniform1f(gl.getUniformLocation(this.program, 'iTime'), milliseconds / 1000);
        gl.uniform3f(gl.getUniformLocation(this.program, 'iResolution'), width, height, 1);
        gl.uniform4f(gl.getUniformLocation(this.program, 'iMouse'), 0, 0, 0, 0);
        gl.drawArrays(gl.TRIANGLES, 0, 3);
        const error = gl.getError();
        if (error !== gl.NO_ERROR) throw new Error('WebGL2 preview drawing failed: ' + error);
    }

    dispose() {
        this.clear();
        this.gl.deleteTexture(this.sourceTexture);
        this.gl.deleteVertexArray(this.vertexArray);
    }
}
window.ShaderPreviewRenderer = ShaderPreviewRenderer;
